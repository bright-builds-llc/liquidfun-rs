export function option(
  id: string,
  label: string,
): { readonly id: string; readonly label: string } {
  return { id, label };
}

export function runtimePreset(
  id: string,
  label: string,
  values: readonly { readonly id: string; readonly label: string }[],
): SceneControl {
  return { id, label, kind: "preset", recreates: false, values };
}

export function action(id: string, label: string): SceneControl {
  return { id, label, kind: "action", recreates: false };
}

export function sceneSource(fileName: string): string {
  return `crates/liquidfun-wasm/src/scene/${fileName}`;
}
